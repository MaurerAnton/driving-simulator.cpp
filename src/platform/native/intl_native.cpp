struct Civil {
  long year = 1970;
  int month = 1;
  int day = 1;
  /** 0: Sunday */
  int weekday = 4;
  int hour = 0;
  int minute = 0;
};

/** The day and the time of a moment that is `ms` after 1970 in its own time zone's count. */
Civil civilOf(double ms) {
  const double dayMs = 86400000.0;
  const double days = std::floor(ms / dayMs);
  const double rest = ms - days * dayMs;
  Civil c;
  c.hour = static_cast<int>(rest / 3600000.0);
  c.minute = static_cast<int>(std::fmod(rest, 3600000.0) / 60000.0);
  const long z0 = static_cast<long>(days);
  c.weekday = static_cast<int>(((z0 % 7) + 11) % 7);   // (1970-01-01 was a Thursday)
  // (days → year, month, day: the usual count from 0000-03-01 in eras of 400 years)
  const long z = z0 + 719468;
  const long era = (z >= 0 ? z : z - 146096) / 146097;
  const long doe = z - era * 146097;
  const long yoe = (doe - doe / 1460 + doe / 36524 - doe / 146096) / 365;
  const long doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
  const long mp = (5 * doy + 2) / 153;
  c.day = static_cast<int>(doy - (153 * mp + 2) / 5 + 1);
  c.month = static_cast<int>(mp < 10 ? mp + 3 : mp - 9);
  c.year = yoe + era * 400 + (c.month <= 2 ? 1 : 0);
  return c;
}

const char* const MONTHS_DE[] = {"Januar", "Februar", "März", "April", "Mai", "Juni", "Juli", "August", "September", "Oktober", "November", "Dezember"};
/** the short names inside a date ("5. Sept. 2026") and alone ("Sep") */
const char* const MONTHS_DE_SHORT[] = {"Jan.", "Feb.", "März", "Apr.", "Mai", "Juni", "Juli", "Aug.", "Sept.", "Okt.", "Nov.", "Dez."};
const char* const MONTHS_DE_ALONE[] = {"Jan", "Feb", "Mär", "Apr", "Mai", "Jun", "Jul", "Aug", "Sep", "Okt", "Nov", "Dez"};
const char* const MONTHS_EN[] = {"January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"};
const char* const MONTHS_EN_SHORT[] = {"Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"};
const char* const DAYS_DE[] = {"Sonntag", "Montag", "Dienstag", "Mittwoch", "Donnerstag", "Freitag", "Samstag"};
const char* const DAYS_DE_SHORT[] = {"So", "Mo", "Di", "Mi", "Do", "Fr", "Sa"};
const char* const DAYS_EN[] = {"Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"};
const char* const DAYS_EN_SHORT[] = {"Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"};

std::string two(long v) { return padStart(std::to_string(v), 2, '0'); }

/** The parts asked for: 0 – not; else how. */
struct Parts {
  enum { None = 0, Numeric = 1, TwoDigit = 2, Short = 3, Long = 4 };
  int weekday = None, day = None, month = None, year = None, hour = None, minute = None;
};

int partOf(const char* name, const std::string& value, bool words) {
  if (value.empty()) return Parts::None;
  if (!words) {
    if (value == "numeric") return Parts::Numeric;
    if (value == "2-digit") return Parts::TwoDigit;
    refuse("Value " + value + " out of range for Intl.DateTimeFormat options property " + name);
  }
  if (value == "short") return Parts::Short;
  if (value == "long") return Parts::Long;
  // (the month may be a number as well)
  if (std::strcmp(name, "month") == 0) {
    if (value == "numeric") return Parts::Numeric;
    if (value == "2-digit") return Parts::TwoDigit;
  }
  if (value == "narrow") unknownHere(std::string(name) + ": \"narrow\"");
  refuse("Value " + value + " out of range for Intl.DateTimeFormat options property " + name);
}

std::string datePart(Style s, const Parts& p, const Civil& c) {
  const bool de = s == Style::De;
  const bool W = p.weekday != Parts::None, D = p.day != Parts::None, M = p.month != Parts::None, Y = p.year != Parts::None;
  const bool text = p.month == Parts::Short || p.month == Parts::Long;
  const std::string year = p.year == Parts::TwoDigit ? two(((c.year % 100) + 100) % 100) : std::to_string(c.year);
  // one part alone
  if (W && !D && !M && !Y) return p.weekday == Parts::Long ? (de ? DAYS_DE : DAYS_EN)[c.weekday] : (de ? DAYS_DE_SHORT : DAYS_EN_SHORT)[c.weekday];
  if (D && !W && !M && !Y) return p.day == Parts::TwoDigit ? two(c.day) : std::to_string(c.day);
  if (Y && !W && !D && !M) return year;
  const char* monthName = "";
  if (text) {
    const int m = c.month - 1;
    if (p.month == Parts::Long) monthName = (de ? MONTHS_DE : MONTHS_EN)[m];
    else if (de) monthName = D || Y ? MONTHS_DE_SHORT[m] : MONTHS_DE_ALONE[m];
    // (British English shortens September to four letters)
    else monthName = s == Style::Gb && m == 8 ? "Sept" : MONTHS_EN_SHORT[m];
  }
  if (M && !W && !D && !Y) return text ? monthName : p.month == Parts::TwoDigit ? two(c.month) : std::to_string(c.month);
  const std::string weekday = !W ? "" : p.weekday == Parts::Long ? (de ? DAYS_DE : DAYS_EN)[c.weekday] : de ? std::string(DAYS_DE_SHORT[c.weekday]) + "." : DAYS_EN_SHORT[c.weekday];
  const std::string dayText = p.day == Parts::TwoDigit ? two(c.day) : std::to_string(c.day);
  // the weekday with the day of the month
  if (W && D && !M && !Y) return s == Style::De ? weekday + ", " + dayText + "." : s == Style::Us ? dayText + " " + weekday : weekday + " " + dayText;
  if (!M || (W && !D)) unknownHere("these parts of a date together");

  // the day with the month, the month with the year, all three
  std::string date;
  if (text) {
    if (s == Style::De) date = (D ? dayText + ". " : "") + monthName + (Y ? " " + year : "");
    else if (s == Style::Gb) date = (D ? dayText + " " : "") + monthName + (Y ? " " + year : "");
    else date = std::string(monthName) + (D ? " " + dayText : "") + (Y ? (D ? ", " : " ") + year : "");
  } else {
    // (British and Canadian dates in numbers always have two digits for day and month)
    const bool wide = s == Style::Gb || s == Style::Ca;
    const std::string d = wide || p.day == Parts::TwoDigit ? two(c.day) : std::to_string(c.day);
    const std::string m = (wide && (D || Y)) || p.month == Parts::TwoDigit ? two(c.month) : std::to_string(c.month);
    switch (s) {
      case Style::De: date = D ? d + "." + m + "." + (Y ? year : "") : m + "/" + year; break;
      case Style::Gb: date = (D ? d + "/" : "") + m + (Y ? "/" + year : ""); break;
      case Style::Us: date = m + (D ? "/" + d : "") + (Y ? "/" + year : ""); break;
      case Style::Ca: date = (Y ? year + "-" : "") + m + (D ? "-" + d : ""); break;
    }
  }
  if (!W) return date;
  // (British English writes the comma only before a date with its year)
  return weekday + (s == Style::Gb && !Y ? " " : ", ") + date;
}

std::string timePart(Style s, const Parts& p, const Civil& c) {
  if (p.hour == Parts::None || p.minute == Parts::None) unknownHere("the hour without the minute (or the minute without the hour)");
  if (s == Style::De || s == Style::Gb) {
    // ("5:07" only where the hour is asked for as it is and the minute with two digits)
    const bool plain = p.hour == Parts::Numeric && p.minute == Parts::TwoDigit;
    return (plain ? std::to_string(c.hour) : two(c.hour)) + ":" + two(c.minute);
  }
  const int h = c.hour % 12 == 0 ? 12 : c.hour % 12;
  const char* half = s == Style::Ca ? (c.hour < 12 ? "a.m." : "p.m.") : (c.hour < 12 ? "AM" : "PM");
  return (p.hour == Parts::TwoDigit ? two(h) : std::to_string(h)) + ":" + two(c.minute) + " " + half;
}

