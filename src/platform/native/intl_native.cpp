std::string formatNumber(double value, const std::string& locale, const NumberFormat& o) {
  const Tag tag = parseTag(locale);
  // the options, refused as Intl refuses them
  if (!oneOf(o.style, {"", "decimal", "unit"})) {
    if (oneOf(o.style, {"percent", "currency"})) unknownHere("style \"" + o.style + "\"");
    refuse("Value " + o.style + " out of range for Intl.NumberFormat options property style");
  }
  const bool unit = o.style == "unit";
  if (unit && o.unit.empty()) refuse("Invalid unit argument for Intl.NumberFormat() ''");
  if (!oneOf(o.unitDisplay, {"", "short", "long"})) {
    if (o.unitDisplay == "narrow") unknownHere("unitDisplay \"narrow\"");
    refuse("Value " + o.unitDisplay + " out of range for Intl.NumberFormat options property unitDisplay");
  }
  if (!oneOf(o.notation, {"", "standard", "compact"})) {
    if (oneOf(o.notation, {"scientific", "engineering"})) unknownHere("notation \"" + o.notation + "\"");
    refuse("Value " + o.notation + " out of range for Intl.NumberFormat options property notation");
  }
  const bool compact = o.notation == "compact";
  if (o.minimumFractionDigits < -1 || o.minimumFractionDigits > 100) refuse("minimumFractionDigits value is out of range.");
  if (o.maximumFractionDigits < -1 || o.maximumFractionDigits > 100) refuse("maximumFractionDigits value is out of range.");
  if (o.minimumFractionDigits >= 0 && o.maximumFractionDigits >= 0 && o.minimumFractionDigits > o.maximumFractionDigits) refuse("maximumFractionDigits value is out of range.");
  if (o.maximumSignificantDigits != -1 && (o.maximumSignificantDigits < 1 || o.maximumSignificantDigits > 21)) refuse("maximumSignificantDigits value is out of range.");
  if (compact && unit) unknownHere("a compact number with a unit");

  const LocaleRow& row = rowOf(tag);
  const char* pattern = nullptr;
  const char display = o.unitDisplay == "long" ? 'l' : 's';
  if (unit && !unitPattern(row, o.unit, display, "other")) {
    // (Intl knows many more units; a name that is none at all it refuses too)
    unknownHere("unit \"" + o.unit + "\"");
  }

  Digits g;
  if (o.maximumSignificantDigits != -1) {
    g.by = Digits::By::Significant;
    g.maxSignificant = o.maximumSignificantDigits;
    g.minFraction = 0;
  } else if (o.minimumFractionDigits != -1 || o.maximumFractionDigits != -1) {
    g.minFraction = o.minimumFractionDigits != -1 ? o.minimumFractionDigits : 0;
    g.maxFraction = o.maximumFractionDigits != -1 ? o.maximumFractionDigits : (g.minFraction > 3 ? g.minFraction : 3);
  } else if (compact) g.by = Digits::By::Compact;

  // the locale's own digits and their signs, unless Western ones are asked for
  const bool own = row.zero != 0 && o.numberingSystem != "latn";
  const std::string decimal = own ? row.ownDecimal : row.decimal;
  const std::string groupSign = own ? row.ownGroup : row.group;
  const char32_t zeroDigit = own ? row.zero : 0;

  std::string number;
  const char* category = "other";
  if (std::isnan(value)) number = row.nan;
  else {
    const double size = std::fabs(value);
    std::string body;
    if (std::isinf(size)) body = row.infinity;
    else {
      Decimal d = shortest(size);
      const char* word = "";
      int minGroup = row.minGroup;
      if (compact) {
        // the word goes by the size of the number; one that is rounded up into the next size takes that one's ("999.9K" is "1M")
        minGroup = minGroup > 2 ? minGroup : 2;
        if (!d.digits.empty()) {
          const int magnitude = d.point - 1;
          Compact c = compactOf(tag, magnitude);
          Decimal scaled = d;
          scaled.point -= c.exponent;
          roundBy(scaled, g);
          if (!scaled.digits.empty() && scaled.point - 1 + c.exponent != magnitude) {
            const Compact next = compactOf(tag, magnitude + 1);
            if (next.exponent != c.exponent) {
              scaled.point -= next.exponent - c.exponent;
              roundBy(scaled, g);
              c = next;
            }
          }
          word = c.word;
          d = scaled;
        }
      } else roundBy(d, g);
      const Shown s = show(d, g.by == Digits::By::Fraction ? g.minFraction : 0);
      body = ownDigits(grouped(s.whole, minGroup, row.group2, groupSign), zeroDigit);
      if (!s.fraction.empty()) body += decimal + ownDigits(s.fraction, zeroDigit);
      body += word;
      if (unit) category = pluralOf(tag.language, s.whole, s.fraction);
    }
    number = (std::signbit(value) ? row.minus : "") + body;
  }
  if (!unit) return number;
  pattern = unitPattern(row, o.unit, display, category);
  return replaceAll(pattern, "{0}", number);
}

std::string formatDate(double ms, const std::string& locale, const DateTimeFormat& o) {
  const Tag tag = parseTag(locale);
  if (!std::isfinite(ms)) refuse("Invalid time value");
  Parts p;
  p.weekday = partOf("weekday", o.weekday, true);
  p.day = partOf("day", o.day, false);
  p.month = partOf("month", o.month, true);
  p.year = partOf("year", o.year, false);
  p.hour = partOf("hour", o.hour, false);
  p.minute = partOf("minute", o.minute, false);
  const bool parts = p.weekday || p.day || p.month || p.year || p.hour || p.minute;
  if (!oneOf(o.dateStyle, {"", "medium"})) {
    if (oneOf(o.dateStyle, {"full", "long", "short"})) unknownHere("dateStyle \"" + o.dateStyle + "\"");
    refuse("Value " + o.dateStyle + " out of range for Intl.DateTimeFormat options property dateStyle");
  }
  if (!oneOf(o.timeStyle, {"", "short"})) {
    if (oneOf(o.timeStyle, {"full", "long", "medium"})) unknownHere("timeStyle \"" + o.timeStyle + "\"");
    refuse("Value " + o.timeStyle + " out of range for Intl.DateTimeFormat options property timeStyle");
  }
  const bool styled = !o.dateStyle.empty() || !o.timeStyle.empty();
  if (styled && parts) refuse("Invalid option : option");   // (Intl's TypeError: a style and single parts do not go together)

  // the moment in the zone's own count
  const std::string zone = toLowerAscii(o.timeZone);
  double local = ms;
  if (zone.empty() || zone == "europe/berlin") local = ms - timezoneOffsetMin(ms) * 60000.0;   // (this machine's zone is Germany's: plat_native.cpp)
  else if (zone != "utc") unknownHere("timeZone \"" + o.timeZone + "\"");
  const Civil c = civilOf(local);

  const Style s = styleOf(tag);
  if (styled) {
    std::string out;
    if (!o.dateStyle.empty()) {
      Parts d;
      d.year = Parts::Numeric;
      d.day = s == Style::De ? Parts::TwoDigit : Parts::Numeric;
      d.month = s == Style::De ? Parts::TwoDigit : Parts::Short;
      out = datePart(s, d, c);
    }
    if (!o.timeStyle.empty()) {
      Parts t;
      t.hour = s == Style::De || s == Style::Gb ? Parts::TwoDigit : Parts::Numeric;
      t.minute = Parts::TwoDigit;
      out += (out.empty() ? "" : ", ") + timePart(s, t, c);
    }
    return out;
  }
  if (!parts) {
    // (nothing asked for: the day, the month and the year in numbers)
    p.day = p.month = p.year = Parts::Numeric;
  }
  const bool date = p.weekday || p.day || p.month || p.year;
  const bool time = p.hour || p.minute;
  if (!time) return datePart(s, p, c);
  if (!date) return timePart(s, p, c);
  // (a date with its month in full is joined to the time by a word)
  const char* glue = p.month == Parts::Long ? (s == Style::De ? " um " : " at ") : ", ";
  return datePart(s, p, c) + glue + timePart(s, p, c);
}

std::string formatList(const std::vector<std::string>& items, const std::string& locale, const ListFormat& o) {
  const Tag tag = parseTag(locale);
  if (!oneOf(o.style, {"", "long"})) {
    if (oneOf(o.style, {"short", "narrow"})) unknownHere("a list of style \"" + o.style + "\"");
    refuse("Value " + o.style + " out of range for Intl.ListFormat options property style");
  }
  if (!oneOf(o.type, {"", "conjunction"})) {
    if (oneOf(o.type, {"disjunction", "unit"})) unknownHere("a list of type \"" + o.type + "\"");
    refuse("Value " + o.type + " out of range for Intl.ListFormat options property type");
  }
  const LocaleRow& row = rowOf(tag);
  const size_t n = items.size();
  if (n == 0) return "";
  if (n == 1) return items[0];
  if (n == 2) return items[0] + row.pair + items[1];
  std::string out = items[0] + row.start;
  for (size_t i = 1; i + 1 < n; i++) out += items[i] + (i + 2 < n ? row.middle : row.end);
  return out + items[n - 1];
}

