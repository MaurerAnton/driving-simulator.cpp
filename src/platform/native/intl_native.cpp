/** A number that is not negative, in decimal digits: 0.d1 d2 d3 … × 10^point (no digits: zero). */
struct Decimal {
  std::string digits;
  int point = 0;
};

void strip(Decimal& d) {
  while (!d.digits.empty() && d.digits.back() == '0') d.digits.pop_back();
  if (d.digits.empty()) d.point = 0;
}

/** The fewest digits that tell the number from its neighbours – what ICU (and String(x)) start from. */
Decimal shortest(double x) {
  Decimal d;
  if (x == 0) return d;
  char buf[48];
  const auto r = std::to_chars(buf, buf + sizeof buf, x, std::chars_format::scientific);
  const std::string_view s(buf, static_cast<size_t>(r.ptr - buf));
  const size_t e = s.find('e');
  for (char c : s.substr(0, e))
    if (c != '.') d.digits += c;
  d.point = std::atoi(std::string(s.substr(e + 1)).c_str()) + 1;
  strip(d);
  return d;
}

/** Keep the first `keep` digits; a half and more goes up (away from zero). */
void roundTo(Decimal& d, int keep) {
  if (keep >= static_cast<int>(d.digits.size())) return;
  if (keep < 0) {
    d = Decimal{};
    return;
  }
  const bool up = d.digits[static_cast<size_t>(keep)] >= '5';
  d.digits.resize(static_cast<size_t>(keep));
  if (up) {
    int i = keep - 1;
    while (i >= 0 && d.digits[static_cast<size_t>(i)] == '9') d.digits[static_cast<size_t>(i--)] = '0';
    if (i >= 0) d.digits[static_cast<size_t>(i)]++;
    else {
      d.digits.insert(d.digits.begin(), '1');
      d.point++;
    }
  }
  strip(d);
}

/** How a number is to be rounded and filled. */
struct Digits {
  enum class By { Fraction, Significant, Compact } by = By::Fraction;
  int minFraction = 0;
  int maxFraction = 3;
  int maxSignificant = 21;
};

void roundBy(Decimal& d, const Digits& g) {
  if (g.by == Digits::By::Significant) roundTo(d, g.maxSignificant);
  // (a compact number: whole, but with two digits that count – "1.2K", "12K")
  else if (g.by == Digits::By::Compact) roundTo(d, d.point > 2 ? d.point : 2);
  else roundTo(d, d.point + g.maxFraction);
}

struct Shown {
  std::string whole;
  std::string fraction;
};

Shown show(const Decimal& d, int minFraction) {
  Shown s;
  const int n = static_cast<int>(d.digits.size());
  if (n == 0) s.whole = "0";
  else if (d.point <= 0) {
    s.whole = "0";
    s.fraction = std::string(static_cast<size_t>(-d.point), '0') + d.digits;
  } else if (d.point >= n) s.whole = d.digits + std::string(static_cast<size_t>(d.point - n), '0');
  else {
    s.whole = d.digits.substr(0, static_cast<size_t>(d.point));
    s.fraction = d.digits.substr(static_cast<size_t>(d.point));
  }
  while (static_cast<int>(s.fraction.size()) < minFraction) s.fraction += '0';
  return s;
}

/** The digits before the decimal sign in groups: three, then `group2` each; not at all below `minGroup` digits in the first group. */
std::string grouped(const std::string& whole, int minGroup, int group2, const std::string& sign) {
  if (whole.size() < static_cast<size_t>(3 + minGroup)) return whole;
  std::string out = whole.substr(whole.size() - 3);
  size_t left = whole.size() - 3;
  while (left > 0) {
    const size_t take = left < static_cast<size_t>(group2) ? left : static_cast<size_t>(group2);
    out = whole.substr(left - take, take) + sign + out;
    left -= take;
  }
  return out;
}

void appendUtf8(std::string& out, char32_t c) {
  if (c < 0x80) out += static_cast<char>(c);
  else if (c < 0x800) {
    out += static_cast<char>(0xC0 | (c >> 6));
    out += static_cast<char>(0x80 | (c & 0x3F));
  } else if (c < 0x10000) {
    out += static_cast<char>(0xE0 | (c >> 12));
    out += static_cast<char>(0x80 | ((c >> 6) & 0x3F));
    out += static_cast<char>(0x80 | (c & 0x3F));
  } else {
    out += static_cast<char>(0xF0 | (c >> 18));
    out += static_cast<char>(0x80 | ((c >> 12) & 0x3F));
    out += static_cast<char>(0x80 | ((c >> 6) & 0x3F));
    out += static_cast<char>(0x80 | (c & 0x3F));
  }
}

/** The Western digits of a text as the locale's own (zero: its first digit; 0: they are the Western ones). */
std::string ownDigits(const std::string& text, char32_t zero) {
  if (!zero) return text;
  std::string out;
  for (char c : text) {
    if (c >= '0' && c <= '9') appendUtf8(out, zero + static_cast<char32_t>(c - '0'));
    else out += c;
  }
  return out;
}

/** The word of a compact number of that size (10^magnitude) and what the number is divided by (10^exponent). */
struct Compact {
  int exponent;
  const char* word;
};
Compact compactOf(const Tag& t, int magnitude) {
  const int step = magnitude < 3 ? 0 : magnitude < 6 ? 1 : magnitude < 9 ? 2 : magnitude < 12 ? 3 : 4;
  if (t.language == "de") {
    // (German has no short word for thousands)
    static const Compact DE[] = {{0, ""}, {0, ""}, {6, "\xc2\xa0Mio."}, {9, "\xc2\xa0Mrd."}, {12, "\xc2\xa0" "Bio."}};
    return DE[step];
  }
  if (t.language == "en" && (t.region.empty() || t.region == "US")) {
    static const Compact US[] = {{0, ""}, {3, "K"}, {6, "M"}, {9, "B"}, {12, "T"}};
    return US[step];
  }
  static const Compact GB[] = {{0, ""}, {3, "k"}, {6, "m"}, {9, "bn"}, {12, "tn"}};
  return GB[step];
}

// --- the plural form of a number ------------------------------------------------------

/** the number the last `k` digits make ("1234", 2 → 34) */
long tail(const std::string& digits, size_t k) {
  long v = 0;
  for (size_t i = digits.size() > k ? digits.size() - k : 0; i < digits.size(); i++) v = v * 10 + (digits[i] - '0');
  return v;
}
/** do the digits make the number n (a small one)? */
bool is(const std::string& digits, long n) {
  size_t first = 0;
  while (first + 1 < digits.size() && digits[first] == '0') first++;
  return digits.substr(first) == std::to_string(n);
}
bool zero(const std::string& digits) {
  for (char c : digits)
    if (c != '0') return false;
  return true;
}
bool in(long v, long from, long to) { return v >= from && v <= to; }

/**
 * CLDR's plural rules (cardinal) of the game's languages, on a number as it is written:
 * `whole` its digits before the decimal sign (i), `fraction` those behind it as shown
 * (f, and their count v).  n is the number itself.
 */
const char* pluralOf(const std::string& lang, const std::string& whole, const std::string& fraction) {
  const bool v0 = fraction.empty();
  const bool integer = zero(fraction);   // n is a whole number
  const long i10 = tail(whole, 1), i100 = tail(whole, 2);
  const long f10 = tail(fraction, 1), f100 = tail(fraction, 2);
  const bool n0 = integer && is(whole, 0), n1 = integer && is(whole, 1), n2 = integer && is(whole, 2);
  // "e = 0 and i != 0 and i % 1000000 = 0 and v = 0": a number of whole millions
  const bool millions = v0 && !is(whole, 0) && tail(whole, 6) == 0;

  if (lang == "id" || lang == "vi" || lang == "zh" || lang == "ja" || lang == "ko") return "other";
  if (lang == "de" || lang == "en" || lang == "nl" || lang == "ur") return is(whole, 1) && v0 ? "one" : "other";
  if (lang == "it" || lang == "pt") return is(whole, 1) && v0 ? "one" : millions ? "many" : "other";   // (pt: the rule of Portugal)
  if (lang == "es") return n1 ? "one" : millions ? "many" : "other";
  if (lang == "fr") return is(whole, 0) || is(whole, 1) ? "one" : millions ? "many" : "other";
  if (lang == "sq" || lang == "el" || lang == "hu" || lang == "tr" || lang == "bg") return n1 ? "one" : "other";
  if (lang == "hi" || lang == "bn" || lang == "fa") return is(whole, 0) || n1 ? "one" : "other";
  if (lang == "cs") return is(whole, 1) && v0 ? "one" : v0 && (is(whole, 2) || is(whole, 3) || is(whole, 4)) ? "few" : !v0 ? "many" : "other";
  if (lang == "pl") {
    if (is(whole, 1) && v0) return "one";
    if (v0 && in(i10, 2, 4) && !in(i100, 12, 14)) return "few";
    if (v0 && ((!is(whole, 1) && in(i10, 0, 1)) || in(i10, 5, 9) || in(i100, 12, 14))) return "many";
    return "other";
  }
  if (lang == "hr") {
    if ((v0 && i10 == 1 && i100 != 11) || (!v0 && f10 == 1 && f100 != 11)) return "one";
    if ((v0 && in(i10, 2, 4) && !in(i100, 12, 14)) || (!v0 && in(f10, 2, 4) && !in(f100, 12, 14))) return "few";
    return "other";
  }
  if (lang == "ro") {
    if (is(whole, 1) && v0) return "one";
    if (!v0 || n0 || (!n1 && in(i100, 1, 19))) return "few";
    return "other";
  }
  if (lang == "ru" || lang == "uk") {
    if (v0 && i10 == 1 && i100 != 11) return "one";
    if (v0 && in(i10, 2, 4) && !in(i100, 12, 14)) return "few";
    if (v0 && (i10 == 0 || in(i10, 5, 9) || in(i100, 11, 14))) return "many";
    return "other";
  }
  if (lang == "ar") {
    if (n0) return "zero";
    if (n1) return "one";
    if (n2) return "two";
    if (integer && in(i100, 3, 10)) return "few";
    if (integer && in(i100, 11, 99)) return "many";
    return "other";
  }
  // a language that is not the game's: as English
  return is(whole, 1) && v0 ? "one" : "other";
}

