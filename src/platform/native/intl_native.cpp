struct Tag {
  /** "de" */
  std::string language;
  /** "DE" ("": none given) */
  std::string region;
};

bool alpha(char c) { return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z'); }
bool digitChar(char c) { return c >= '0' && c <= '9'; }

/** The language and the region of a tag such as "de-DE", "zh-Hans-CN", "ar"; an ill-formed one is refused as Intl refuses it. */
Tag parseTag(const std::string& locale) {
  const std::vector<std::string> parts = split(locale, "-");
  auto bad = [&]() { refuse("Invalid language tag: " + locale); };
  for (size_t i = 0; i < parts.size(); i++) {
    const std::string& p = parts[i];
    if (p.empty() || p.size() > 8) bad();
    for (char c : p)
      if (!alpha(c) && !(i > 0 && digitChar(c))) bad();
  }
  // the language: two or three letters, or five to eight
  if (parts[0].size() < 2 || parts[0].size() == 4) bad();
  Tag t;
  t.language = toLowerAscii(parts[0]);
  for (size_t i = 1; i < parts.size(); i++) {
    const std::string& p = parts[i];
    // (a single letter begins an extension: "-u-nu-latn")
    if (p.size() == 1) break;
    if (p.size() == 2 && alpha(p[0]) && alpha(p[1])) {
      t.region = toUpperAscii(p);
      break;
    }
  }
  return t;
}

